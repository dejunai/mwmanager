r"""Found by the CR-28 stress run (round 1): Tidy sent an omw2mwse conversion's MWSE loader and its hosted OpenMW Lua
(MWSE\mods\mwsuite\openmw\<mod>\main.lua, ...\omw\*.omwscripts, ...\omw\scripts\) to Off\<mod>\OpenMW, because a
folder on the way was named "openmw" or "scripts", so the converted mod deployed without its loader. OpenMW never
reads inside MWSE\, so nothing there is OpenMW-only, whatever its folders are called."""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import mwmanager_install as ext  # noqa: E402
import mwmanager_upstream  # noqa: E402
import py_compat  # noqa: E402

LOADER = (b"-- LeaveTheLightsOff: MWSE loader generated by omw2mwse 0.2.3.\n"
          b'local ok, omwcompat = pcall(require, "omwcompat")\n')


def _build(mod, files):
    for rel, data in files.items():
        (mod / rel).parent.mkdir(parents=True, exist_ok=True)
        (mod / rel).write_bytes(data)


class MwseTreeIsNeverOpenMW(unittest.TestCase):
    def _tidy(self, files, name):
        tmp = py_compat.TemporaryDirectory(ignore_cleanup_errors=True)
        self.addCleanup(tmp.cleanup)
        staging = Path(tmp.name) / "staging"
        mod = staging / name
        _build(mod, files)
        with mwmanager_upstream.use_manager_dir(tmp.name):
            Path(tmp.name, "outputs").mkdir(exist_ok=True)
            tidy = mwmanager_upstream.compose_tidy()
            plan = ext.plan_mod(str(mod))
            self.assertNotIsInstance(plan, str)
            review = dict(tidy.REVIEW)
            failed = ext.apply(plan, str(staging))
        return mod, plan, failed, review

    def test_converted_mod_keeps_its_loader_and_hosted_scripts(self):
        base = "MWSE/mods/mwsuite/openmw/LeaveTheLightsOff/"
        mod, plan, failed, review = self._tidy({
            base + "main.lua": LOADER,
            base + "omw/LeaveTheLightsOff.omwscripts": b"GLOBAL: scripts/LeaveTheLightsOff/LTLO_g.lua\n",
            base + "omw/scripts/LeaveTheLightsOff/LTLO_g.lua": b"return {}\n",
            "MWSE/lib/omwcompat.lua": b"return {}\n",
            "Off/LeaveTheLightsOff/OpenMW/LeaveTheLightsOff.omwscripts": b"GLOBAL: x.lua\n",
            "meshes/omwc/ltlo/0c4afea3.nif": b"nif",
        }, "mwsuite - OpenMW - Leave The Lights Off")
        self.assertEqual(failed, [])
        for rel in ("main.lua", "omw/LeaveTheLightsOff.omwscripts", "omw/scripts/LeaveTheLightsOff/LTLO_g.lua"):
            self.assertTrue((mod / base / rel).is_file(), rel)
        self.assertFalse(any("main.lua" in str(src) for src, _dst, _why in plan))
        self.assertNotIn(str(mod), review)            # not reported as an OpenMW-only mod either

    def test_mwse_mod_with_a_scripts_folder_stays_deployed(self):
        mod, _plan, failed, review = self._tidy({
            "MWSE/mods/SomeAuthor/Thing/main.lua": b"require('SomeAuthor.Thing.scripts.util')\n",
            "MWSE/mods/SomeAuthor/Thing/scripts/util.lua": b"return {}\n",
            "MWSE/mods/SomeAuthor/Thing/l10n/en.lua": b"return {}\n",
        }, "Thing-12345")
        self.assertEqual(failed, [])
        self.assertTrue((mod / "MWSE/mods/SomeAuthor/Thing/scripts/util.lua").is_file())
        self.assertTrue((mod / "MWSE/mods/SomeAuthor/Thing/l10n/en.lua").is_file())
        self.assertNotIn(str(mod), review)

    def test_root_openmw_scripts_still_go_to_off(self):
        mod, _plan, failed, _review = self._tidy({
            "MWSE/mods/Dual/main.lua": b"return {}\n",
            "Dual.omwscripts": b"PLAYER: scripts/Dual/p.lua\n",
            "scripts/Dual/p.lua": b"return {}\n",
        }, "Dual-777")
        self.assertEqual(failed, [])
        self.assertTrue((mod / "MWSE/mods/Dual/main.lua").is_file())
        self.assertFalse((mod / "Dual.omwscripts").exists())
        self.assertFalse((mod / "scripts").exists())
        self.assertTrue(any(p.name == "p.lua" for p in (mod / "Off").rglob("*")))


if __name__ == "__main__":
    unittest.main()
