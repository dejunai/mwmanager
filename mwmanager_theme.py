"""Shared styling for MWManager's Tk windows.

One dark "ash and brass" theme: warm near-black surfaces, parchment text, a brass accent for the
primary action, and a small set of status colours. Everything visual is defined here as tokens so
the main window, the mock FOMOD and every dialog stay consistent.

Public API (used by mwmanager_gui.py and mock_fomod.py):
  COLORS        colour tokens (the original keys are kept for compatibility)
  FONTS         font tuples, resolved to installed families by apply_theme()
  SPACE         spacing scale in pixels
  apply_theme   configure ttk styles, named fonts and classic-widget defaults on a root
  center        place a window over the window that opened it, or in the middle of the desktop
"""

from __future__ import annotations

import tkinter as tk
from tkinter import font as tkfont
from tkinter import ttk

COLORS = {
    # surfaces, darkest to lightest
    "canvas": "#17140f",        # window background
    "surface": "#211c16",       # cards, lists, tree rows
    "surface_alt": "#2b241c",   # buttons, headings, striped rows
    "raised": "#362d23",        # hovered buttons
    "field": "#100e0b",         # entries, log panes
    "border": "#4d3f2e",
    "border_soft": "#30281f",
    "select": "#5a4426",
    # text
    "text": "#e9dfc9",
    "text_strong": "#f6edd9",
    "muted": "#b3a389",
    "faint": "#857760",
    # accent and status
    "gold": "#d6b26c",          # brass: primary actions, headings
    "gold_hi": "#e8c886",
    "on_gold": "#1b150d",       # text on a brass button
    "green": "#97b885",         # done / installed / enabled
    "teal": "#7fb6ad",          # progress
    "blue": "#93b0dc",          # fixed / generated by MWManager
    "amber": "#e0aa4c",         # new / needs attention
    "rust": "#d18c6f",
    "red": "#e2806f",           # errors / destructive
}

SPACE = {"xs": 4, "sm": 6, "md": 10, "lg": 14, "xl": 20}

_UI_FAMILIES = ("Segoe UI Variable Text", "Segoe UI", "Selawik", "Inter", "Noto Sans", "DejaVu Sans")
_MONO_FAMILIES = ("Cascadia Mono", "Cascadia Code", "Consolas", "JetBrains Mono", "DejaVu Sans Mono")

# Placeholders until apply_theme() resolves installed families; tuples work before a root exists.
FONTS = {
    "body": ("Segoe UI", 10), "small": ("Segoe UI", 9), "bold": ("Segoe UI", 10, "bold"),
    "h1": ("Segoe UI", 17, "bold"), "h2": ("Segoe UI", 11, "bold"), "h3": ("Segoe UI", 10, "bold"),
    "mono": ("Cascadia Mono", 9), "mono_small": ("Cascadia Mono", 9),
    "button": ("Segoe UI", 10), "button_bold": ("Segoe UI", 10, "bold"),
}


def _pick(available: set[str], wanted: tuple[str, ...]) -> str:
    for name in wanted:
        if name.casefold() in available:
            return name
    return wanted[-1]


def _resolve_fonts(root: tk.Misc) -> None:
    try:
        available = {name.casefold() for name in tkfont.families(root)}
    except tk.TclError:
        return
    ui = _pick(available, _UI_FAMILIES)
    mono = _pick(available, _MONO_FAMILIES)
    FONTS.update({
        "body": (ui, 10), "small": (ui, 9), "bold": (ui, 10, "bold"),
        "h1": (ui, 17, "bold"), "h2": (ui, 11, "bold"), "h3": (ui, 10, "bold"),
        "mono": (mono, 9), "mono_small": (mono, 9),
        "button": (ui, 10), "button_bold": (ui, 10, "bold"),
    })
    for name, family, size in (("TkDefaultFont", ui, 10), ("TkTextFont", ui, 10), ("TkMenuFont", ui, 10),
                               ("TkHeadingFont", ui, 10), ("TkCaptionFont", ui, 10),
                               ("TkSmallCaptionFont", ui, 9), ("TkTooltipFont", ui, 9),
                               ("TkFixedFont", mono, 9)):
        try:
            tkfont.nametofont(name, root=root).configure(family=family, size=size)
        except (tk.TclError, TypeError):
            try:
                tkfont.nametofont(name).configure(family=family, size=size)
            except tk.TclError:
                pass


def apply_theme(root: tk.Misc) -> ttk.Style:
    """Apply the shared theme to ttk and classic Tk widgets under `root`."""
    _resolve_fonts(root)
    root.configure(background=COLORS["canvas"])
    style = ttk.Style(root)
    try:
        style.theme_use("clam")
    except tk.TclError:
        pass
    c, f = COLORS, FONTS

    # ── base ──────────────────────────────────────────────────────────────────────────────
    style.configure(".", background=c["canvas"], foreground=c["text"], font=f["body"],
                    bordercolor=c["border"], darkcolor=c["surface"], lightcolor=c["surface_alt"],
                    troughcolor=c["field"], focuscolor=c["gold"], selectbackground=c["select"],
                    selectforeground=c["text_strong"], insertcolor=c["gold"])
    style.configure("TFrame", background=c["canvas"])
    style.configure("Card.TFrame", background=c["surface"], relief="solid", borderwidth=1,
                    bordercolor=c["border_soft"])
    style.configure("Header.TFrame", background=c["surface"])
    style.configure("Toolbar.TFrame", background=c["canvas"])
    style.configure("Statusbar.TFrame", background=c["surface"])
    style.configure("TSeparator", background=c["border_soft"])

    # ── labels ────────────────────────────────────────────────────────────────────────────
    style.configure("TLabel", background=c["canvas"], foreground=c["text"])
    style.configure("H1.TLabel", font=f["h1"], foreground=c["gold"])
    style.configure("H2.TLabel", font=f["h2"], foreground=c["text_strong"])
    style.configure("H3.TLabel", font=f["h3"], foreground=c["text_strong"])
    style.configure("Muted.TLabel", foreground=c["muted"], font=f["small"])
    style.configure("Tooltip.TLabel", background=c["raised"], foreground=c["text"], font=f["small"],
                    padding=(8, 5), relief="solid", borderwidth=1, bordercolor=c["border"])
    style.configure("Faint.TLabel", foreground=c["faint"], font=f["small"])
    for bg_name in ("Header", "Card", "Statusbar"):
        bg = c["surface"]
        style.configure(f"{bg_name}.TLabel", background=bg, foreground=c["text"])
        style.configure(f"{bg_name}.H1.TLabel", background=bg, font=f["h1"], foreground=c["gold"])
        style.configure(f"{bg_name}.H2.TLabel", background=bg, font=f["h2"], foreground=c["text_strong"])
        style.configure(f"{bg_name}.Muted.TLabel", background=bg, foreground=c["muted"], font=f["small"])
    style.configure("Status.TLabel", background=c["surface"], foreground=c["muted"], font=f["small"],
                    padding=(SPACE["md"], 5))
    for tone in ("gold", "green", "teal", "blue", "amber", "red", "muted", "faint"):
        style.configure(f"{tone.title()}.TLabel", foreground=c[tone])
        style.configure(f"Chip.{tone.title()}.TLabel", background=c["surface_alt"], foreground=c[tone],
                        font=f["small"], padding=(8, 2))
    style.configure("TLabelframe", background=c["canvas"], bordercolor=c["border"])
    style.configure("TLabelframe.Label", background=c["canvas"], foreground=c["gold"], font=f["h3"])

    # ── buttons ───────────────────────────────────────────────────────────────────────────
    style.configure("TButton", background=c["surface_alt"], foreground=c["text"], bordercolor=c["border"],
                    lightcolor=c["surface_alt"], darkcolor=c["surface_alt"], padding=(12, 5),
                    font=f["button"], focusthickness=1, focuscolor=c["gold"], relief="flat")
    style.map("TButton",
              background=[("disabled", c["surface"]), ("pressed", c["select"]), ("active", c["raised"])],
              foreground=[("disabled", c["faint"]), ("active", c["text_strong"])],
              bordercolor=[("disabled", c["border_soft"]), ("focus", c["gold"]), ("active", c["gold"])],
              lightcolor=[("active", c["raised"])], darkcolor=[("active", c["raised"])])
    style.configure("Primary.TButton", background=c["gold"], foreground=c["on_gold"], bordercolor=c["gold"],
                    lightcolor=c["gold"], darkcolor=c["gold"], font=f["button_bold"], padding=(16, 6))
    style.map("Primary.TButton",
              background=[("disabled", c["surface"]), ("pressed", c["gold"]), ("active", c["gold_hi"])],
              foreground=[("disabled", c["faint"]), ("active", c["on_gold"])],
              bordercolor=[("disabled", c["border_soft"]), ("active", c["gold_hi"])],
              lightcolor=[("active", c["gold_hi"])], darkcolor=[("active", c["gold_hi"])])
    # Generate Patches with nothing to do: still clickable (Ctrl/Shift-click), visibly quiet.
    style.configure("GenerateIdle.TButton", background=c["surface"], foreground=c["muted"],
                    bordercolor=c["border_soft"], font=f["button"], padding=(16, 6))
    style.map("GenerateIdle.TButton", background=[("active", c["surface_alt"])],
              foreground=[("active", c["text"])], bordercolor=[("active", c["border"])])
    style.configure("Danger.TButton", foreground=c["red"])
    style.map("Danger.TButton", foreground=[("disabled", c["faint"]), ("active", c["red"])],
              bordercolor=[("active", c["red"])])
    style.configure("Toolbar.TButton", padding=(10, 4))
    style.configure("MasterSave.TButton", background=c["gold"], foreground=c["on_gold"], bordercolor=c["gold"],
                    lightcolor=c["gold"], darkcolor=c["gold"], font=f["button_bold"], padding=(18, 8))
    style.map("MasterSave.TButton", background=[("active", c["gold_hi"])], foreground=[("active", c["on_gold"])])

    # ── inputs ────────────────────────────────────────────────────────────────────────────
    style.configure("TCheckbutton", background=c["canvas"], foreground=c["text"], indicatorbackground=c["field"],
                    indicatorforeground=c["gold"], indicatorrelief="flat")
    style.map("TCheckbutton", background=[("active", c["canvas"])], foreground=[("disabled", c["faint"])],
              indicatorbackground=[("selected", c["field"]), ("active", c["surface_alt"])])
    style.configure("TRadiobutton", background=c["canvas"], foreground=c["text"], indicatorbackground=c["field"],
                    indicatorforeground=c["gold"])
    style.map("TRadiobutton", background=[("active", c["canvas"])], foreground=[("disabled", c["faint"])])
    style.configure("TEntry", fieldbackground=c["field"], foreground=c["text"], insertcolor=c["gold"],
                    bordercolor=c["border"], lightcolor=c["field"], darkcolor=c["field"], padding=(6, 4))
    style.map("TEntry", bordercolor=[("focus", c["gold"])], lightcolor=[("focus", c["gold"])])
    style.configure("TCombobox", fieldbackground=c["field"], background=c["surface_alt"], foreground=c["text"],
                    arrowcolor=c["gold"], bordercolor=c["border"], padding=(6, 4))
    style.map("TCombobox", fieldbackground=[("readonly", c["field"])], foreground=[("readonly", c["text"])],
              selectbackground=[("readonly", c["select"])], bordercolor=[("focus", c["gold"])])
    style.configure("TSpinbox", fieldbackground=c["field"], foreground=c["text"], arrowcolor=c["gold"],
                    bordercolor=c["border"])

    # ── lists ─────────────────────────────────────────────────────────────────────────────
    style.configure("Treeview", background=c["surface"], fieldbackground=c["surface"], foreground=c["text"],
                    bordercolor=c["border_soft"], lightcolor=c["surface"], darkcolor=c["surface"],
                    rowheight=26, font=f["body"])
    style.map("Treeview", background=[("selected", c["select"])], foreground=[("selected", c["text_strong"])])
    style.configure("Treeview.Heading", background=c["surface_alt"], foreground=c["muted"], relief="flat",
                    padding=(8, 6), font=f["h3"], bordercolor=c["border_soft"], lightcolor=c["surface_alt"],
                    darkcolor=c["surface_alt"])
    style.map("Treeview.Heading", background=[("active", c["raised"])], foreground=[("active", c["gold"])])

    # ── containers and chrome ─────────────────────────────────────────────────────────────
    style.configure("TNotebook", background=c["canvas"], bordercolor=c["border_soft"], tabmargins=(0, 4, 0, 0))
    style.configure("TNotebook.Tab", background=c["surface"], foreground=c["muted"], padding=(14, 6),
                    bordercolor=c["border_soft"])
    style.map("TNotebook.Tab", background=[("selected", c["surface_alt"])], foreground=[("selected", c["gold"])])
    style.configure("TProgressbar", background=c["teal"], troughcolor=c["field"], bordercolor=c["border_soft"],
                    lightcolor=c["teal"], darkcolor=c["teal"], thickness=8)
    style.configure("TScrollbar", background=c["surface_alt"], troughcolor=c["surface"], arrowcolor=c["muted"],
                    bordercolor=c["surface"], lightcolor=c["surface_alt"], darkcolor=c["surface_alt"],
                    gripcount=0, arrowsize=12)
    style.map("TScrollbar", background=[("active", c["raised"])], arrowcolor=[("active", c["gold"])])
    style.configure("Job.Vertical.TScrollbar", background=c["gold"], troughcolor=c["field"],
                    bordercolor=c["border"], lightcolor=c["gold"], darkcolor=c["gold"], gripcount=0)
    style.map("Job.Vertical.TScrollbar", background=[("active", c["gold_hi"])])
    style.configure("TPanedwindow", background=c["canvas"])

    for option, value in {
        "*Menu.background": c["surface"], "*Menu.foreground": c["text"],
        "*Menu.activeBackground": c["select"], "*Menu.activeForeground": c["text_strong"],
        "*Menu.disabledForeground": c["faint"], "*Menu.relief": "flat", "*Menu.borderWidth": 1,
        "*Text.background": c["field"], "*Text.foreground": c["text"], "*Text.insertBackground": c["gold"],
        "*Text.selectBackground": c["select"], "*Text.selectForeground": c["text_strong"],
        "*Text.font": "TkTextFont", "*Text.relief": "flat", "*Text.highlightThickness": 1,
        "*Text.highlightBackground": c["border_soft"], "*Text.highlightColor": c["border"],
        "*Listbox.background": c["surface"], "*Listbox.foreground": c["text"],
        "*Listbox.selectBackground": c["select"], "*Listbox.selectForeground": c["text_strong"],
        "*Listbox.relief": "flat", "*Listbox.highlightThickness": 0, "*Listbox.borderWidth": 0,
        "*Listbox.activeStyle": "none",
        "*Canvas.background": c["canvas"], "*Canvas.highlightThickness": 0,
        "*Toplevel.background": c["canvas"],
    }.items():
        root.option_add(option, value)

    # New dialog shells default to the Windows light colour even when all their ttk children are
    # themed. Colour each top-level as soon as it is mapped.
    def darken_dialog(event):
        if isinstance(event.widget, tk.Toplevel):
            try:
                event.widget.configure(background=c["canvas"])
            except tk.TclError:
                pass

    root.bind_all("<Map>", darken_dialog, add="+")
    return style


def center(window: tk.Misc, parent: tk.Misc | None = None, width: int | None = None,
           height: int | None = None) -> None:
    """Centre `window` over `parent`'s window when that is on screen, else on the desktop, and keep it on screen.
    Without a size the window's own requested size is used (call this after its contents are built)."""
    window.update_idletasks()
    width = width or window.winfo_reqwidth()
    height = height or window.winfo_reqheight()
    screen_w, screen_h = window.winfo_screenwidth(), window.winfo_screenheight()
    x, y = (screen_w - width) // 2, (screen_h - height) // 2
    if parent is not None:
        try:
            top = parent.winfo_toplevel()
            top.update_idletasks()
            if top.winfo_viewable():
                x = top.winfo_rootx() + (top.winfo_width() - width) // 2
                y = top.winfo_rooty() + (top.winfo_height() - height) // 2
        except tk.TclError:
            pass
    x = max(0, min(x, screen_w - width))
    y = max(0, min(y, screen_h - height))
    window.geometry(f"{width}x{height}+{x}+{y}")


# One palette for a major master's state in every window (staging review and Major Masters).
# Enabled is the ☑ mark, not a colour, so it reads the same at every state.
MASTER_STATUS = {
    "deployed": ("green", "Green — deployed into Data Files"),
    "staged": ("blue", "Blue — staged, not deployed yet"),
    "not_staged": ("amber", "Amber — not staged"),
    "locked": ("red", "Red — required by another master; cannot be disabled"),
    "problem": ("rust", "Rust — missing or needs repair"),
    "skipped": ("muted", "Grey — skipped"),
}


def master_status_tags(tree: ttk.Treeview) -> None:
    for tag, (tone, _label) in MASTER_STATUS.items():
        tree.tag_configure(tag, foreground=COLORS[tone])


def master_status_legend(parent, keys, wraplength=660) -> None:
    for key in keys:
        tone, label = MASTER_STATUS[key]
        ttk.Label(parent, text=label, foreground=COLORS[tone], wraplength=wraplength, justify="left").pack(anchor="w")


def tree_tags(tree: ttk.Treeview) -> None:
    """Shared row tags for load-order style trees: zebra striping plus status foregrounds."""
    c = COLORS
    tree.tag_configure("odd", background=c["surface_alt"])
    tree.tag_configure("core", foreground=c["faint"])
    tree.tag_configure("fixed_patch", foreground=c["blue"])
    tree.tag_configure("new_plugin", foreground=c["amber"])
    tree.tag_configure("disabled_row", foreground=c["muted"])
